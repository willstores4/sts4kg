#!/usr/bin/env python3
"""Embed the reviewed Mozilla root bundle; no trust downloads occur at runtime."""
import base64
import hashlib
import json
import re
import ssl
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHA256 = '427c064216761a1e72a8b30f0d954d08cb6e4435a82091fb865afd20c8497285'

def generate():
    data = (ROOT / 'assets/service/cacert.pem').read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError('CA bundle differs from the reviewed 2026-11-05 source')
    blocks = re.findall(rb'-----BEGIN CERTIFICATE-----\n([A-Za-z0-9+/=\n]+)-----END CERTIFICATE-----', data)
    if len(blocks) != 118:
        raise ValueError('Unexpected trusted root count')
    certificates = []
    for block in blocks:
        base64.b64decode(block.replace(b'\n', b''), validate=True)
        certificates.append('-----BEGIN CERTIFICATE-----\n' + block.decode('ascii') + '-----END CERTIFICATE-----\n')
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.load_verify_locations(cadata=''.join(certificates))
    if context.cert_store_stats()['x509_ca'] != len(blocks):
        raise ValueError('CA bundle contains an invalid or duplicate root')
    lines = ['// Generated by tools/embed_trust.py. Mozilla CA data: MPL-2.0.',
             '#pragma once', '#include <stddef.h>', '#include <orbis/Ssl.h>']
    for index, pem in enumerate(certificates):
        lines.append('static char portalTrustRoot%d[] = %s;' % (index, json.dumps(pem.replace('\n', '\r\n'))))
    lines.append('static SslPem portalTrustRecords[] = {')
    lines.extend('    {portalTrustRoot%d, sizeof(portalTrustRoot%d)-1},' % (i, i) for i in range(len(blocks)))
    lines.append('};\nstatic SslPem* portalTrustRoots[] = {')
    lines.extend('    &portalTrustRecords[%d],' % i for i in range(len(blocks)))
    lines.extend(['};', 'static const size_t portalTrustCount = sizeof(portalTrustRoots)/sizeof(portalTrustRoots[0]);',
                  'static const char portalTrustSHA256[] = "%s";' % SHA256])
    output = ROOT / 'build/trusted_roots.h'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n')
    print('Embedded %d reviewed Mozilla roots (%s).' % (len(blocks), SHA256))

if __name__ == '__main__':
    generate()
